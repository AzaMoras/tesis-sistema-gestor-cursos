#!/bin/sh
(
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=app_password="$APP_DB_PASSWORD" <<'SQL'
CREATE ROLE aula_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD :'app_password';
ALTER DATABASE aula_verde OWNER TO aula_app;
REVOKE ALL ON DATABASE aula_verde FROM PUBLIC;
GRANT CONNECT, TEMPORARY ON DATABASE aula_verde TO aula_app;
ALTER SCHEMA public OWNER TO aula_app;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
SQL
)
